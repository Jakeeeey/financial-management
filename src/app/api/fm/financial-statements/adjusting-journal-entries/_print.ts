import { NextResponse } from "next/server";
import { jsPDF } from "jspdf";
import autoTable, { type UserOptions } from "jspdf-autotable";
import type { AdjustingEntry, AjeAccess, AjePrintReport } from "@/modules/financial-management/financial-statements/adjusting-journal-entries/types";
import { formatDateTime } from "@/modules/financial-management/financial-statements/adjusting-journal-entries/components/formatters";
import { AjePrintError, loadEntryPrint, loadSummaryPrint, printMoney } from "./_print-data";

type Company = { company_name: string; company_address?: string };

async function company(): Promise<Company> {
  const base = process.env.NEXT_PUBLIC_API_BASE_URL?.replace(/\/+$/, "");
  const token = process.env.DIRECTUS_STATIC_TOKEN;
  if (!base || !token) throw new AjePrintError("Company information is not configured for printing.", 503);
  const response = await fetch(base + "/items/company?filter[company_id][_eq]=1&fields=company_name,company_address&limit=1", {
    headers: { Authorization: "Bearer " + token }, cache: "no-store", signal: AbortSignal.timeout(15_000),
  });
  if (!response.ok) throw new AjePrintError("Company information could not be loaded for printing.", 503);
  const data = await response.json();
  if (!data.data?.[0]?.company_name) throw new AjePrintError("Company information is unavailable for printing.", 503);
  return data.data[0];
}

const entryNumber = (entry: AdjustingEntry) => entry.jeNo || "Record #" + entry.id;
const pdfMoney = (value: number | string) => printMoney(value).replace("\u20b1", "PHP ");
const entryType = (entry: AdjustingEntry) => entry.entryOrigin === "SYSTEM" ? "System journal"
  : entry.entryKind === "REVERSAL" ? (entry.reversalMode === "PARTIAL" ? "Partial reversal" : "Full reversal") : "Adjustment";
function date(value: string | null | undefined) {
  if (!value) return "—";
  const parsed = new Date(value.slice(0, 10) + "T00:00:00Z");
  return Number.isFinite(parsed.getTime()) ? new Intl.DateTimeFormat("en-PH", {
    dateStyle: "medium", timeZone: "UTC",
  }).format(parsed) : value;
}

function document(landscape: boolean, profile: Company, title: string) {
  const doc = new jsPDF({ format: "a4", orientation: landscape ? "landscape" : "portrait", compress: true });
  doc.setProperties({ title });
  const width = doc.internal.pageSize.getWidth() - 24;
  doc.setFont("helvetica", "bold").setFontSize(11);
  const companyName = doc.splitTextToSize(profile.company_name, width);
  doc.text(companyName, 12, 15);
  let y = 15 + companyName.length * 5;
  if (profile.company_address) {
    doc.setFont("helvetica", "normal").setFontSize(8);
    const address = doc.splitTextToSize(profile.company_address, width);
    doc.text(address, 12, y);
    y += address.length * 4;
  }
  doc.setFont("helvetica", "bold").setFontSize(13).text(title, 12, y + 5);
  return { doc, y: y + 11 };
}

function table(doc: jsPDF, title: string, options: UserOptions) {
  autoTable(doc, {
    theme: "grid", rowPageBreak: "avoid", margin: { left: 12, right: 12, top: 22, bottom: 22 },
    styles: { font: "helvetica", fontSize: 8, cellPadding: 2, textColor: 30, overflow: "linebreak" },
    headStyles: { fillColor: [35, 58, 90], textColor: 255 },
    footStyles: { fillColor: [237, 241, 247], textColor: 30 },
    willDrawPage: () => {
      if (doc.getCurrentPageInfo().pageNumber > 1) {
        doc.setFont("helvetica", "bold").setFontSize(9).setTextColor(30).text(title, 12, 13);
      }
    },
    ...options,
  });
  return (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 5;
}

function footer(doc: jsPDF, actor: AjeAccess, generatedAt: string) {
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page++) {
    doc.setPage(page).setFont("helvetica", "normal").setFontSize(7).setTextColor(85);
    const height = doc.internal.pageSize.getHeight(), width = doc.internal.pageSize.getWidth();
    doc.setDrawColor(210).line(12, height - 16, width - 12, height - 16);
    doc.text(doc.splitTextToSize("Generated by " + actor.userName + " | " + formatDateTime(generatedAt), width - 48), 12, height - 11);
    doc.text("Page " + page + " / " + pages, width - 12, height - 11, { align: "right" });
  }
}

export async function entryPdf(entry: AdjustingEntry, actor: AjeAccess, generatedAt: string, profile: Company): Promise<ArrayBuffer> {
  const title = "Adjusting Journal Entry · " + entryNumber(entry);
  const { doc, y } = document(false, profile, title);
  const rows = [
    ["Adjustment number", entryNumber(entry)], ["Status / entry type", entry.status + " · " + entryType(entry)],
    ["Accounting date", date(entry.transactionDate)], ["Reference", entry.reference || "—"],
    ["Division", entry.divisionName || "None"], ["Narration", entry.description || "—"],
    ...(entry.sourceJeNo ? [["Original journal", [entry.sourceJeNo, entry.sourceTransactionRef].filter(Boolean).join(" / ")]] : []),
    ...(entry.sourceModule ? [["Source module", entry.sourceModule]] : []),
    ...(entry.originalEntryId ? [["Original adjustment record", String(entry.originalEntryId)]] : []),
    ...(entry.lastPostingError ? [["Last posting error", entry.lastPostingError]] : []),
  ];
  let nextY = table(doc, title, { startY: y, body: rows,
    columnStyles: { 0: { cellWidth: 43, fontStyle: "bold", fillColor: [244, 246, 249] }, 1: { cellWidth: 143 } } });
  nextY = table(doc, title, { startY: nextY,
    head: [["Account", "Department", "Line description", "Debit", "Credit"]],
    body: entry.details.length ? entry.details.map(line => [[line.accountNumber, line.accountTitle].filter(Boolean).join(" - ") || "—",
      line.departmentName || "—", line.description || "—", pdfMoney(line.debit), pdfMoney(line.credit)])
      : [[{ content: "No journal lines recorded.", colSpan: 5, styles: { halign: "center" } }]],
    foot: [[{ content: "Totals", colSpan: 3 }, pdfMoney(entry.totalDebit), pdfMoney(entry.totalCredit)],
      [{ content: "Debit / credit difference", colSpan: 3 }, { content: pdfMoney(entry.variance), colSpan: 2, styles: { halign: "right" } }]],
    showFoot: "lastPage",
    columnStyles: { 0: { cellWidth: 57 }, 1: { cellWidth: 32 }, 2: { cellWidth: 51 },
      3: { cellWidth: 23, halign: "right", fontSize: 7 }, 4: { cellWidth: 23, halign: "right", fontSize: 7 } } });
  const workflow = [
    ["Created", entry.creatorName, entry.dateCreated], ["Submitted", entry.submittedByName, entry.submittedAt],
    ["Historical approval", entry.approvedByName, entry.approvedAt], ["Posted", entry.postedByName, entry.datePosted],
    ["Rejected", entry.rejectedByName, entry.rejectedAt], ["Cancelled", entry.cancelledByName, entry.cancelledAt],
  ].filter(([, name, timestamp]) => name || timestamp);
  if (workflow.length) table(doc, title, { startY: nextY, head: [["Workflow", "User", "Recorded at (PHT)"]],
    body: workflow.map(([action, name, timestamp]) => [action || "", name || "Not recorded", formatDateTime(timestamp)]),
    columnStyles: { 0: { cellWidth: 35 }, 1: { cellWidth: 86 }, 2: { cellWidth: 65 } } });
  footer(doc, actor, generatedAt);
  return doc.output("arraybuffer");
}

export async function summaryPdf(report: AjePrintReport, params: URLSearchParams, profile: Company): Promise<ArrayBuffer> {
  const title = "Adjusting Journal Entries Summary";
  const { doc, y } = document(true, profile, title);
  const startDate = params.get("startDate");
  const endDate = params.get("endDate");
  const dateScope = !startDate && !endDate ? "All dates"
    : (startDate ? date(startDate) : "From beginning") + " to " + (endDate ? date(endDate) : "Present");
  const filters = [
    "Search: " + (params.get("search") || "All"), "Status: " + (params.get("status") || "All statuses"),
    "Workspace: " + (params.get("workspace") || "All entries"),
    "Queue: " + (params.get("queue") || "all"), "Unbalanced entries only: " + (params.get("unbalancedOnly") === "true" ? "Yes" : "No"),
    "Accounting dates: " + dateScope,
    "Division: " + (params.get("divisionId") ? "#" + params.get("divisionId") : "All"),
    "Department: " + (params.get("departmentId") ? "#" + params.get("departmentId") : "All"),
    "Account type: " + (params.get("accountTypeId") ? "#" + params.get("accountTypeId") : "All"),
    ...(params.get("sourceJeNo") ? ["Original journal: " + params.get("sourceJeNo")] : []),
    "Sort: " + params.get("sort"), "Currency: PHP", "Records: " + report.totalRecords + " (all matching pages)",
    "Generated at (PHT): " + formatDateTime(report.generatedAt),
  ];
  doc.setFont("helvetica", "normal").setFontSize(8);
  const filterLines = doc.splitTextToSize(filters.join(" | "), 273);
  doc.text(filterLines, 12, y);
  const tableY = y + filterLines.length * 4 + 10;
  doc.text("Export scope: every entry matching the filters above across all pages. Summary cards count all workflow statuses.", 12, tableY - 4);
  table(doc, title, { startY: tableY,
    head: [["Journal / reference", "Accounting date", "Narration / original", "Division", "Status / type", "Debit", "Credit", "Created / submitted / historical approval / posted"]],
    body: report.entries.length ? report.entries.map(entry => [
      entryNumber(entry) + (entry.reference ? "\n" + entry.reference : ""), date(entry.transactionDate),
      (entry.description || "—") + (entry.sourceJeNo ? "\nOriginal: " + [entry.sourceJeNo, entry.sourceTransactionRef].filter(Boolean).join(" / ") : ""),
      entry.divisionName || "—", entry.status + "\n" + entryType(entry), pdfMoney(entry.totalDebit), pdfMoney(entry.totalCredit),
      ["Created: " + (entry.creatorName || "—"), "Submitted: " + (entry.submittedByName || "—"),
        "Historical approval: " + (entry.approvedByName || "—"), "Posted: " + (entry.postedByName || "—"),
        ...(entry.datePosted ? ["Posted at: " + formatDateTime(entry.datePosted)] : [])].join("\n"),
    ]) : [[{ content: "No adjusting entries match these filters.", colSpan: 8, styles: { halign: "center" } }]],
    foot: [[{ content: "Filtered totals (all matching entries)", colSpan: 5 }, pdfMoney(report.totalDebit), pdfMoney(report.totalCredit), ""]],
    showFoot: "lastPage", styles: { font: "helvetica", fontSize: 7, cellPadding: 1.8, textColor: 30, overflow: "linebreak" },
    columnStyles: { 0: { cellWidth: 30 }, 1: { cellWidth: 21 }, 2: { cellWidth: 57 }, 3: { cellWidth: 25 },
      4: { cellWidth: 25 }, 5: { cellWidth: 27, halign: "right" }, 6: { cellWidth: 27, halign: "right" }, 7: { cellWidth: 61 } } });
  footer(doc, report.generatedBy, report.generatedAt);
  return doc.output("arraybuffer");
}

export async function ajePdfResponse(input: { id: string } | { query: URLSearchParams }) {
  let cookies: string[] = [];
  try {
    let bytes: ArrayBuffer, filename: string;
    if ("id" in input) {
      const data = await loadEntryPrint(input.id);
      cookies = data.cookies;
      bytes = await entryPdf(data.entry, data.actor, data.generatedAt, await company());
      filename = (data.entry.jeNo || "adjustment-" + input.id) + ".pdf";
    } else {
      const data = await loadSummaryPrint(input.query);
      cookies = data.cookies;
      bytes = await summaryPdf(data.report, data.params, await company());
      filename = "adjusting-entries-summary.pdf";
    }
    const response = new NextResponse(bytes, { headers: { "Content-Type": "application/pdf",
      "Content-Disposition": 'inline; filename="' + filename.replace(/[^a-zA-Z0-9._-]/g, "_") + '"',
      "Cache-Control": "private, no-store", "X-Content-Type-Options": "nosniff" } });
    for (const cookie of cookies) response.headers.append("Set-Cookie", cookie);
    return response;
  } catch (error) {
    if (!(error instanceof AjePrintError)) console.error("AJE PDF generation failed.", {
      type: "id" in input ? "entry" : "summary",
      ...("id" in input ? { entryId: input.id } : {}),
      error: error instanceof Error ? error.message : "Unknown error",
    });
    const response = NextResponse.json({ message: error instanceof AjePrintError ? error.message : "The PDF could not be generated. Please try again." },
      { status: error instanceof AjePrintError ? error.status : 502, headers: { "Cache-Control": "private, no-store" } });
    for (const cookie of [...cookies, ...(error instanceof AjePrintError ? error.cookies : [])]) response.headers.append("Set-Cookie", cookie);
    return response;
  }
}
