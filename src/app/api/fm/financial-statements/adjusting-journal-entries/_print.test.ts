import assert from "node:assert/strict";
import { test } from "node:test";
import { inflateSync } from "node:zlib";
import type { AdjustingEntry, AjePrintReport } from "@/modules/financial-management/financial-statements/adjusting-journal-entries/types";
import { entryPdf, summaryPdf } from "./_print";

const actor = { userId: 24, userName: "Print Tester" };
const generatedAt = "2026-10-22T07:00:00Z";
const company = { company_name: "AJE Print Test Company", company_address: "Marikina, Philippines" };
const entry = {
  id: 900045, jeNo: "AJE-900045", transactionDate: "2026-10-22", status: "Posted",
  entryOrigin: "MANUAL", entryKind: "ADJUSTMENT", reference: "PRINT-TEST",
  description: "Adjustment with signed amounts and supporting journal context.", divisionName: "Main Office",
  sourceJeNo: "JE-100", sourceTransactionRef: "SOURCE-100", sourceModule: "Disbursement",
  creatorName: "Print Tester", dateCreated: generatedAt, postedByName: "Reviewer", datePosted: generatedAt,
  totalDebit: 1200, totalCredit: 1200, variance: 0,
  details: [
    { id: 1, coaId: 1, accountNumber: "4001", accountTitle: "Cash", departmentName: "Finance", debit: 1234.5, credit: 0 },
    { id: 2, coaId: 2, accountNumber: "4002", accountTitle: "Expense correction", debit: -34.5, credit: 0 },
    { id: 3, coaId: 3, accountNumber: "4003", accountTitle: "Clearing", debit: 0, credit: 1200 },
  ],
} as AdjustingEntry;

function report(overrides: Partial<AjePrintReport> = {}): AjePrintReport {
  return { entries: [entry], totalRecords: 1, totalDebit: "1200.00", totalCredit: "1200.00",
    generatedBy: actor, generatedAt, ...overrides };
}

function inspectPdf(bytes: ArrayBuffer) {
  const source = Buffer.from(bytes).toString("latin1");
  assert.ok(source.startsWith("%PDF-"));
  assert.ok(source.trimEnd().endsWith("%%EOF"));
  assert.match(source, /\/BaseFont \/Helvetica\b/);
  assert.match(source, /\/BaseFont \/Helvetica-Bold\b/);
  assert.doesNotMatch(source, /NotoSans|\/FontFile/);
  const streams = Array.from(source.matchAll(/stream\r?\n([\s\S]*?)\r?\nendstream/g), match =>
    inflateSync(Buffer.from(match[1], "latin1")).toString("latin1"));
  const text = streams.join("\n");
  const joinedText = Array.from(text.matchAll(/\(((?:\\.|[^\\)])*)\)/g), match => match[1]).join("").replace(/\s+/g, "");
  return { source, text, joinedText };
}

test("individual PDFs render signed PHP amounts using built-in fonts", async () => {
  const { text } = inspectPdf(await entryPdf(entry, actor, generatedAt, company));
  for (const value of ["AJE-900045", company.company_name, "PHP 1,234.50", "-PHP 34.50", "PHP 0.00", "PHP 1,200.00", "Generated by Print Tester"]) {
    assert.ok(text.includes(value), value);
  }
});

test("summary PDFs preserve authoritative large decimal totals and negative signs", async () => {
  const { joinedText } = inspectPdf(await summaryPdf(report({ totalDebit: "9007199254740993.21", totalCredit: "-1234.50" }),
    new URLSearchParams("workspace=posting&status=Posted&sort=lastActivity,desc"), company));
  for (const value of ["Adjusting Journal Entries Summary", "PHP 9,007,199,254,740,993.21", "-PHP 1,234.50", "Status: Posted", "Workspace: posting"]) {
    assert.ok(joinedText.includes(value.replace(/\s+/g, "")), value);
  }
});

test("empty individual and summary PDFs remain printable", async () => {
  const individual = inspectPdf(await entryPdf({ ...entry, details: [], totalDebit: 0, totalCredit: 0 }, actor, generatedAt, company));
  const summary = inspectPdf(await summaryPdf(report({ entries: [], totalRecords: 0, totalDebit: "0", totalCredit: "0" }), new URLSearchParams(), company));
  assert.ok(individual.text.includes("No journal lines recorded."));
  assert.ok(summary.text.includes("No adjusting entries match these filters."));
  assert.ok(individual.text.includes("PHP 0.00"));
  assert.ok(summary.text.includes("PHP 0.00"));
});

test("multipage entry PDFs retain totals and page-number footers", async () => {
  const details = Array.from({ length: 75 }, (_, index) => ({ ...entry.details[index % entry.details.length],
    description: "Detailed explanation for review, including the reason for this accounting adjustment." }));
  const { source, text } = inspectPdf(await entryPdf({ ...entry, details }, actor, generatedAt, company));
  const pageCount = source.match(/\/Type \/Page\b/g)?.length ?? 0;
  assert.ok(pageCount > 1);
  assert.ok(text.includes(`Page 1 / ${pageCount}`));
  assert.ok(text.includes(`Page ${pageCount} / ${pageCount}`));
  assert.ok(text.includes("Debit / credit difference"));
});
