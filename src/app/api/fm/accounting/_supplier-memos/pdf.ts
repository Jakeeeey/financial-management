import { readFile } from "node:fs/promises";
import path from "node:path";
import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import { memoDateTime, memoMoney, type MemoDetail, type MemoHistoryEvent, type SupplierMemo, type SupplierMemoFilters, type SupplierMemoType } from "@/modules/financial-management/accounting/supplier-memos/types";
import type { MemoActor } from "./access";
import { readRows } from "./directus";

let fonts: Promise<string[]> | undefined;
async function document(format: "a5" | "a4") {
  fonts ||= Promise.all(["Regular", "Bold"].map(async weight =>
    (await readFile(path.join(process.cwd(), "public/fonts/noto-sans/NotoSans-" + weight + ".ttf"))).toString("base64")));
  const [regular, bold] = await fonts;
  const doc = new jsPDF({ format, orientation: format === "a5" ? "portrait" : "landscape", compress: true });
  doc.addFileToVFS("NotoSans-Regular.ttf", regular);
  doc.addFont("NotoSans-Regular.ttf", "NotoSans", "normal");
  doc.addFileToVFS("NotoSans-Bold.ttf", bold);
  doc.addFont("NotoSans-Bold.ttf", "NotoSans", "bold");
  doc.setFont("NotoSans");
  return doc;
}

async function heading(doc: jsPDF, title: string) {
  const [company] = await readRows("company", { company_id: { _eq: 1 } }, "company_id,company_name,company_address", "company_id");
  const width = doc.internal.pageSize.getWidth() - 24;
  doc.setFontSize(11).setFont("NotoSans", "bold");
  const companyLines = doc.splitTextToSize(String(company?.company_name || "Supplier Memos"), width);
  doc.text(companyLines, 12, 15);
  let y = 15 + companyLines.length * 5;
  if (company?.company_address) {
    doc.setFontSize(8).setFont("NotoSans", "normal");
    const address = doc.splitTextToSize(String(company.company_address), width);
    doc.text(address, 12, y);
    y += address.length * 4;
  }
  doc.setFontSize(13).setFont("NotoSans", "bold");
  doc.text(title, 12, y + 6);
  return y + 12;
}

function footer(doc: jsPDF, actor: MemoActor, generatedAt: string) {
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page++) {
    doc.setPage(page).setFont("NotoSans", "normal").setFontSize(7).setTextColor(85);
    const height = doc.internal.pageSize.getHeight(), width = doc.internal.pageSize.getWidth();
    doc.setDrawColor(210).line(12, height - 16, width - 12, height - 16);
    const lines = doc.splitTextToSize("Generated by " + actor.name + " | " + memoDateTime(generatedAt), width - 46);
    doc.text(lines, 12, height - 11);
    doc.text("Page " + page + " / " + pages, width - 12, height - 11, { align: "right" });
  }
}

const date = (value: string) => value?.slice(0, 10) || "-";
const status = (value: string) => value.toUpperCase() === "CANCELLED" ? "CANCELLED" : value;

export async function memoSlip(detail: MemoDetail, history: MemoHistoryEvent[], actor: MemoActor): Promise<ArrayBuffer> {
  const generatedAt = new Date().toISOString();
  const doc = await document("a5");
  const { memo, eligibility } = detail;
  const y = await heading(doc, "Supplier " + (Number(memo.type) === 1 ? "Credit" : "Debit") + " Memo");
  const cancellation = history.find(event => event.action === "CANCEL" && event.outcome === "completed");
  const rows = [
    ["Memo number", memo.memo_number], ["Date", date(memo.date)], ["Status", status(memo.status)],
    ["Supplier", memo.supplierName || "-"], ["GL account", [memo.accountCode, memo.accountName].filter(Boolean).join(" - ")],
    ["Memo reason", memo.reason || "-"], ["Original amount", memoMoney(Number(memo.amount))],
    ["Posted usage", memoMoney(eligibility.appliedAmount)], ["Reserved / unposted", memoMoney(eligibility.reservedAmount)],
    ["Remaining balance", memoMoney(eligibility.remainingAmount)], ["Created by", memo.creatorName || "Not recorded"],
    ["Created at (PHT)", memoDateTime(memo.created_at)],
    ...(memo.status.toUpperCase() === "CANCELLED" ? [["Cancellation", cancellation
      ? cancellation.actorName + " | " + memoDateTime(cancellation.occurredAt) + "\nReason: " + cancellation.reason
      : "Cancellation actor/reason not recorded in application history."]] : []),
    ...(eligibility.ambiguous ? [["Usage requires review", eligibility.blockedReason || "The linked usage cannot be safely attributed."]] : []),
  ];
  autoTable(doc, { startY: y, body: rows, margin: { left: 12, right: 12, top: 15, bottom: 28 },
    styles: { font: "NotoSans", fontSize: 8, cellPadding: 2.2, overflow: "linebreak", textColor: 30 },
    columnStyles: { 0: { cellWidth: 39, fontStyle: "bold", fillColor: [244, 246, 249] }, 1: { cellWidth: 85 } },
    theme: "grid", rowPageBreak: "avoid" });
  footer(doc, actor, generatedAt);
  return doc.output("arraybuffer");
}

export async function memoReport(memos: SupplierMemo[], type: SupplierMemoType, filters: SupplierMemoFilters, actor: MemoActor): Promise<ArrayBuffer> {
  const generatedAt = new Date().toISOString();
  const doc = await document("a4");
  let y = await heading(doc, "Supplier " + (type === 1 ? "Credit" : "Debit") + " Memo Summary");
  const selectedSupplier = memos.find(memo => String(memo.supplier_id) === filters.supplier_id)?.supplierName || filters.supplier_id;
  const selectedAccount = memos.find(memo => String(memo.chart_of_account) === filters.chart_of_account)?.accountName || filters.chart_of_account;
  const description = [
    "Search: " + (filters.search || "All"), "Supplier: " + (selectedSupplier || "All"),
    "Account: " + (selectedAccount || "All"), "Status: " + (filters.status || "All"),
    "Date: " + (filters.date_from || "Any") + " to " + (filters.date_to || "Any"), "Records: " + memos.length,
  ].join(" | ");
  doc.setFont("NotoSans", "normal").setFontSize(8);
  const filterLines = doc.splitTextToSize(description, 273);
  doc.text(filterLines, 12, y);
  y += filterLines.length * 4 + 3;
  const active = memos.filter(memo => memo.status.toUpperCase() !== "CANCELLED");
  const cancelled = memos.filter(memo => memo.status.toUpperCase() === "CANCELLED");
  const sum = (rows: SupplierMemo[], field: "amount" | "appliedAmount" | "reservedAmount" | "remainingAmount") =>
    rows.reduce((total, memo) => total + Number(field === "amount" ? memo.amount : memo.eligibility?.[field] || 0), 0);
  const hasUnknown = active.some(memo => memo.eligibility?.ambiguous);
  const totals = "Active original: " + memoMoney(sum(active, "amount")) + " | Cancelled: " + cancelled.length
    + " (" + memoMoney(sum(cancelled, "amount")) + ") | Usage totals " + (hasUnknown ? "exclude rows marked Needs review." : "are shown below.");
  doc.text(doc.splitTextToSize(totals, 273), 12, y);
  y += 9;
  autoTable(doc, { startY: y, margin: { left: 12, right: 12, top: 15, bottom: 21 },
    head: [["Memo no.", "Date", "Supplier", "GL account", "Reason", "Status", "Original", "Posted", "Reserved", "Remaining"]],
    body: memos.map(memo => [memo.memo_number, date(memo.date), memo.supplierName || "-",
      [memo.accountCode, memo.accountName].filter(Boolean).join(" - "), memo.reason || "-", status(memo.status), memoMoney(Number(memo.amount)),
      memoMoney(memo.eligibility?.appliedAmount ?? null), memoMoney(memo.eligibility?.reservedAmount ?? null), memoMoney(memo.eligibility?.remainingAmount ?? null)]),
    foot: [["Active totals", "", "", "", "", "", memoMoney(sum(active, "amount")), memoMoney(sum(active, "appliedAmount")),
      memoMoney(sum(active, "reservedAmount")), memoMoney(sum(active, "remainingAmount"))]],
    showFoot: "lastPage", theme: "grid", styles: { font: "NotoSans", fontSize: 7, cellPadding: 1.8, overflow: "linebreak", textColor: 30 },
    headStyles: { fillColor: [35, 58, 90], textColor: 255, fontStyle: "bold" }, footStyles: { fillColor: [237, 241, 247], textColor: 30 },
    columnStyles: { 0: { cellWidth: 25 }, 1: { cellWidth: 18 }, 2: { cellWidth: 34 }, 3: { cellWidth: 38 },
      4: { cellWidth: 42 }, 5: { cellWidth: 20 }, 6: { cellWidth: 24, halign: "right" }, 7: { cellWidth: 24, halign: "right" },
      8: { cellWidth: 24, halign: "right" }, 9: { cellWidth: 24, halign: "right" } },
    rowPageBreak: "avoid" });
  if (!memos.length) doc.setFontSize(9).text("No memos match these filters.", 12, y + 20);
  footer(doc, actor, generatedAt);
  return doc.output("arraybuffer");
}
